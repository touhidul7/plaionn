import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import {settingsSchema} from '../src/lib/season-settings-schema.ts';
const form={season_id:'20000000-0000-4000-8000-000000000001',revision:'0',roster_limit:'20',period_count:'3',period_minutes:'20',clock_mode:'stop',win_points:'2',tie_points:'1',loss_points:'0',overtime_loss_points:'1',billing_model:'both',currency:'CAD',team_fee_cents:'1000.10',player_fee_cents:'250.05',registration_opens:'2026-10-01',registration_closes:'2026-10-31',tiebreaker_priority_1:'wins',tiebreaker_priority_2:'goal_difference',tiebreaker_priority_3:'goals_for',tiebreaker_priority_4:'head_to_head',tiebreaker_priority_5:'fewest_penalties'};
test('settings validate dates, integer bounds, and exact monetary amounts',()=>{
 const parsed=settingsSchema.parse(form);
 assert.equal(parsed.team_fee_cents,100010);
 assert.equal(parsed.player_fee_cents,25005);
 assert.deepEqual(parsed.standings_tiebreakers,['wins','goal_difference','goals_for','head_to_head','fewest_penalties']);
 for(const changes of [{team_fee_cents:'1.005'},{team_fee_cents:'-1'},{team_fee_cents:'1000000.01'},{roster_limit:'0'},{period_count:'3.5'},{registration_closes:'2026-09-30'},{registration_opens:'2026-02-30'},{currency:'XYZ'}]) assert.equal(settingsSchema.safeParse({...form,...changes}).success,false,JSON.stringify(changes));
 assert.equal(settingsSchema.safeParse({...form,tiebreaker_priority_5:'wins'}).success,false);
 assert.equal(settingsSchema.safeParse({...form,tiebreaker_priority_1:'unsupported'}).success,false);
 assert.equal(settingsSchema.parse({...form,registration_opens:'',registration_closes:''}).registration_opens,null);
});
test('season configuration enforces league access, audits changes, and rejects stale updates',async()=>{
 const db=new PGlite();
 const league='00000000-0000-4000-8000-000000000001';
 const other='00000000-0000-4000-8000-000000000002';
 const admin='10000000-0000-4000-8000-000000000001';
 const player='10000000-0000-4000-8000-000000000002';
 try{
  await db.exec(`create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key);
   create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
   grant usage on schema auth,public to anon,authenticated;grant execute on function auth.uid() to anon,authenticated;`);
  for(const file of ['202610260001_league_foundation.sql','202610270001_season_settings.sql','202611040001_standings_tiebreakers.sql']) await db.exec(await readFile(new URL('../supabase/migrations/'+file,import.meta.url),'utf8'));
  await db.query('insert into auth.users values($1),($2)',[admin,player]);
  await db.query("insert into leagues(id,name) values($1,'Other League')",[other]);
  await db.query("insert into seasons(id,league_id,name) values($1,$2,'Winter')",[form.season_id,league]);
  await db.query("insert into league_memberships values($1,$2,'commissioner'),($1,$3,'player')",[league,admin,player]);
  await db.exec('set role authenticated');
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[admin]);
  const values={...settingsSchema.parse(form)};
  delete values.revision;
  const record={...values,league_id:league};
  const columns=Object.keys(record);
  const insert='insert into season_settings('+columns.join(',')+') values('+columns.map((_,i)=>'$'+(i+1)).join(',')+')';
  await assert.rejects(db.query(insert,Object.values({...record,league_id:other})),e=>e.code==='42501');
  await db.query(insert,Object.values(record));
  await assert.rejects(db.query('update season_settings set roster_limit=0'),e=>e.code==='23514');
  await db.query('update season_settings set roster_limit=25 where season_id=$1 and revision=1',[form.season_id]);
  const stale=await db.query('update season_settings set roster_limit=30 where season_id=$1 and revision=1 returning season_id',[form.season_id]);
  assert.equal(stale.rows.length,0);
  const audit=await db.query('select actor_id,previous_settings,new_settings from season_settings_audit order by changed_at,id');
  assert.equal(audit.rows.length,2);
  assert.ok(audit.rows.every(row=>row.actor_id===admin));
  assert.ok(audit.rows.some(row=>row.previous_settings?.roster_limit===20&&row.new_settings.roster_limit===25));
  assert.deepEqual(audit.rows[0].new_settings.standings_tiebreakers,['wins','goal_difference','goals_for','head_to_head','fewest_penalties']);
  await assert.rejects(db.query("update season_settings set standings_tiebreakers=array['wins','wins','goals_for','head_to_head','fewest_penalties']"),e=>e.code==='23514');
  await assert.rejects(db.query('delete from season_settings_audit'),e=>e.code==='42501');
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[player]);
  assert.equal((await db.query('select roster_limit from season_settings')).rows[0].roster_limit,25);
  const denied=await db.query('update season_settings set roster_limit=50 returning season_id');
  assert.equal(denied.rows.length,0);
  assert.equal((await db.query('select * from season_settings_audit')).rows.length,0);
  await db.exec('reset role');
  await db.query("delete from league_memberships where user_id=$1",[player]);
  await db.query("insert into league_memberships values($1,$2,'commissioner')",[other,player]);
  await db.exec('set role authenticated');
  assert.equal((await db.query('select * from season_settings')).rows.length,0);
  await db.exec('reset role;set role anon');
  await assert.rejects(db.query('select * from season_settings'),e=>e.code==='42501');
 }finally{await db.close();}
});
